def main():
    rows = []
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))

    missing = [r["id"] for r in rows if r["id"] not in T]
    if missing:
        print(f"ERROR: {len(missing)} rows missing translation:", file=sys.stderr)
        for m in missing:
            print("  ", m, file=sys.stderr)
        sys.exit(1)

    extra = set(T) - {r["id"] for r in rows}
    if extra:
        print(f"WARNING: {len(extra)} translated ids not present in source batch:", extra, file=sys.stderr)

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "source text", "arabic translation", "category", "ref_en", "notes"])
        for r in rows:
            ar, notes = T[r["id"]]
            w.writerow([r["id"], r["source_ko"], ar, r["category"], r["ref_en"], notes])

    print(f"Wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
